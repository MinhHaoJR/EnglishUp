export function useT() {
  const language = useApp((s) => s.settings.language);
  return (key: keyof typeof en) => ({ en, vi })[language][key];
}
export function useBi() {
  const language = useApp((s) => s.settings.language);
  return (vi: string, en: string) => (language === 'vi' ? vi : en);
}
